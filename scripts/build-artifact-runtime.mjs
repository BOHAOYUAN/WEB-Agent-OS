/**
 * Builds the vendored runtime that the Artifacts sandbox renders JSX with.
 *
 * Why vendor at all: the sandbox CSP forbids all network access
 * (`connect-src 'none'`), so React cannot come from a CDN — it has to be a
 * local file. And React 19 dropped its UMD builds entirely, so there is no
 * prebuilt global-bundle to copy: we have to produce the IIFE ourselves.
 *
 * Why the sources are ALSO emitted as an importable module: a srcdoc iframe has
 * an opaque origin, where CSP `'self'` matches nothing and `chrome-extension://`
 * resources are unreachable — so `<script src>` cannot work there and the
 * bundles must be inlined into the srcdoc. `apps/extension/src/generated/`
 * carries them as string constants for that purpose.
 *
 * Two separate bundles on purpose: most artifacts are plain HTML/SVG and never
 * need the JSX transformer, so ~200 KB of Sucrase stays unused.
 *
 * Usage: node scripts/build-artifact-runtime.mjs [--watch]
 */

import { build, context } from "esbuild";
import { mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
/**
 * Where the standalone IIFE bundles land.
 *
 * NOT `dist/`: dist/ IS the extension package, and nothing in the extension
 * loads these two files — the panel gets the runtime as string constants
 * (inlined into the srcdoc), and the E2E script reads them as source text.
 * Keeping them in the package shipped ~427 KB of dead weight (the runtime was
 * in there twice: once as these files, once inside sidepanel.js).
 */
const runtimeDir = join(root, ".tmp-runtime");
const generatedDir = join(root, "apps", "extension", "src", "generated");

const REACT_ENTRY = `
import * as React from "react";
import { createRoot } from "react-dom/client";
globalThis.React = React;
globalThis.ReactDOM = { createRoot };
`;

const SUCRASE_ENTRY = `
import { transform } from "sucrase";
globalThis.__webosTransform = (code) =>
  transform(code, { transforms: ["jsx"], production: true }).code;
`;

const common = {
  bundle: true,
  format: "iife",
  minify: true,
  platform: "browser",
  target: ["chrome116"],
  define: { "process.env.NODE_ENV": '"production"' },
  legalComments: "none",
  logLevel: "warning",
  absWorkingDir: root,
};

const targets = [
  {
    name: "artifact-runtime.js",
    constName: "REACT_RUNTIME_SOURCE",
    stdin: { contents: REACT_ENTRY, resolveDir: root, loader: "js", sourcefile: "artifact-runtime-entry.js" },
  },
  {
    name: "artifact-sucrase.js",
    constName: "SUCRASE_RUNTIME_SOURCE",
    stdin: { contents: SUCRASE_ENTRY, resolveDir: root, loader: "js", sourcefile: "artifact-sucrase-entry.js" },
  },
];

function report(name) {
  return (statSync(join(runtimeDir, name)).size / 1024).toFixed(1) + "kb";
}

export async function buildArtifactRuntime({ watch = false } = {}) {
  mkdirSync(runtimeDir, { recursive: true });

  if (watch) {
    const contexts = await Promise.all(
      targets.map((t) => context({ ...common, stdin: t.stdin, outfile: join(runtimeDir, t.name) })),
    );
    await Promise.all(contexts.map((ctx) => ctx.watch()));
  } else {
    for (const target of targets) {
      await build({ ...common, stdin: target.stdin, outfile: join(runtimeDir, target.name) });
    }
  }

  // Emit the same bundles as inline-able strings for the srcdoc iframe.
  const sources = targets.map((t) => ({
    constName: t.constName,
    source: readFileSync(join(runtimeDir, t.name), "utf8"),
  }));

  for (const { source } of sources) {
    // A literal closing script tag anywhere in a vendored bundle would break
    // the srcdoc it is inlined into. Fail the build rather than ship it.
    if (/<\/script/i.test(source)) {
      throw new Error("vendored runtime contains a literal </script>; inlining it would break the sandbox srcdoc");
    }
  }

  mkdirSync(generatedDir, { recursive: true });
  const module = [
    "/**",
    " * GENERATED by scripts/build-artifact-runtime.mjs — do not edit.",
    " *",
    " * String form of the vendored bundles, inlined into artifact srcdocs",
    " * because a srcdoc iframe (opaque origin) cannot load extension resources.",
    " */",
    ...sources.map((s) => `export const ${s.constName} = ${JSON.stringify(s.source)};`),
    "",
  ].join("\n");
  writeFileSync(join(generatedDir, "artifact-runtime.ts"), module, "utf8");

  console.log("[artifact-runtime] built:");
  for (const target of targets) console.log(`  ${target.name}  ${report(target.name)}`);
}

const invokedDirectly = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (invokedDirectly) {
  await buildArtifactRuntime({ watch: process.argv.includes("--watch") });
}
