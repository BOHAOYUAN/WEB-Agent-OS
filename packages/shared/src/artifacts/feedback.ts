/**
 * Artifact interaction feedback: the return half of the Artifacts loop.
 *
 * A generated component can call `webos.report(...)`; the harness below bridges
 * it out of the opaque-origin iframe via postMessage, and the result is merged
 * into `SystemContext` so the model sees what the user actually did with the
 * thing it built.
 *
 * Security notes that the harness cannot enforce by itself:
 *  - `postMessage` MUST use `"*"` — an opaque-origin iframe has no addressable
 *    origin, so the receiver has to verify `event.source === iframe.contentWindow`
 *    instead of checking `event.origin`. That check lives in the sandbox page,
 *    not here.
 *  - The payload crosses back into the model's context, so it is a bounded
 *    string (`MAX_ARTIFACT_FEEDBACK_CHARS`), never a structured object. Circular
 *    structures are caught and stringified.
 *  - `artifactId` is generated by us ("artifact-<index>"), never taken from
 *    model output, but it is still JSON-escaped before being inlined into the
 *    script for defense in depth.
 */

import {
  ARTIFACT_FEEDBACK_CHANNEL,
  MAX_ARTIFACT_FEEDBACK_CHARS,
  type ArtifactFeedback,
} from "../types/artifacts.js";

const MAX_LABEL_CHARS = 80;

/**
 * Inline script that exposes `window.webos.report()` inside a rendered
 * artifact. Deliberately tiny and dependency-free — it runs before the model's
 * code so the API always exists.
 */
export function artifactHarnessScript(artifactId: string): string {
  const safeId = JSON.stringify(artifactId);
  const channel = JSON.stringify(ARTIFACT_FEEDBACK_CHANNEL);
  return [
    "(function () {",
    `  var ID = ${safeId};`,
    `  var CHANNEL = ${channel};`,
    `  var MAX = ${MAX_ARTIFACT_FEEDBACK_CHARS};`,
    `  var MAX_LABEL = ${MAX_LABEL_CHARS};`,
    "  function asText(v) {",
    "    if (typeof v === 'string') return v;",
    "    if (v === null || v === undefined) return '';",
    "    try { var s = JSON.stringify(v); return s === undefined ? String(v) : s; }",
    "    catch (e) { return String(v); }",
    "  }",
    "  window.webos = {",
    "    report: function (payload, label) {",
    "      var text = asText(payload).slice(0, MAX);",
    "      var name = typeof label === 'string' ? label.slice(0, MAX_LABEL) : '';",
    "      try {",
    "        parent.postMessage({",
    "          type: CHANNEL,",
    "          payload: { artifactId: ID, label: name, payload: text, ts: Date.now() }",
    "        }, '*');",
    "      } catch (e) { /* the frame is gone; dropping the report is correct */ }",
    "      return text;",
    "    }",
    "  };",
    "})();",
  ].join("\n");
}

/**
 * Validate a raw postMessage payload into an ArtifactFeedback.
 * Returns null for anything malformed — cross-frame input is never trusted.
 */
export function normalizeArtifactFeedback(value: unknown): ArtifactFeedback | null {
  if (typeof value !== "object" || value === null) return null;
  const record = value as Record<string, unknown>;
  if (typeof record.artifactId !== "string" || record.artifactId.length === 0) return null;
  if (typeof record.payload !== "string") return null;

  const artifactId = record.artifactId.slice(0, 64);
  const payload = record.payload.slice(0, MAX_ARTIFACT_FEEDBACK_CHARS);
  const label = typeof record.label === "string" ? record.label.slice(0, MAX_LABEL_CHARS) : undefined;
  const ts = typeof record.ts === "number" && Number.isFinite(record.ts) ? record.ts : Date.now();

  return {
    artifactId,
    ...(label ? { label } : {}),
    payload,
    ts,
  };
}

export function isArtifactFeedback(value: unknown): value is ArtifactFeedback {
  return normalizeArtifactFeedback(value) !== null;
}

/**
 * Render feedback as the text injected into the next turn's context.
 * Kept short and clearly attributed so the model can tell "the user clicked X"
 * apart from something it said earlier.
 */
export function formatFeedbackForContext(feedback: ArtifactFeedback): string {
  const label = feedback.label ? `（${feedback.label}）` : "";
  return `用户在 Artifact ${feedback.artifactId} 上的操作${label}结果：${feedback.payload}`;
}

/** Build the postMessage envelope the harness sends. Mirrors the runtime shape. */
export function buildFeedbackMessage(feedback: ArtifactFeedback): {
  type: string;
  payload: ArtifactFeedback;
} {
  return { type: ARTIFACT_FEEDBACK_CHANNEL, payload: feedback };
}
